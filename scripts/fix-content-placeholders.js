const levels = ["grade4", "grade3", "pre2"];
const files = ["vocabulary.json", "questions.json", "mock_exams.json"];

for (const level of levels) {
  for (const file of files) {
    const fullPath = path.join(root, "data", level, file);
    let text = fs.readFileSync(fullPath, "utf8");
    for (const [word, meaning] of Object.entries(zh)) {
      text = text.replaceAll(`${word} 的意思`, meaning);
      text = text.replaceAll(`表示“${meaning}”`, `表示“${meaning}”`);
    }
    fs.writeFileSync(fullPath, text);
  }

  const vocabPath = path.join(root, "data", level, "vocabulary.json");
  const vocabulary = JSON.parse(fs.readFileSync(vocabPath, "utf8"));
  for (const entry of vocabulary) {
    if (zh[entry.word]) entry.chineseMeaning = zh[entry.word];
    if (ja[entry.word]) entry.japaneseMeaning = ja[entry.word];
  }
  fs.writeFileSync(vocabPath, `${JSON.stringify(vocabulary, null, 2)}\n`);
}

